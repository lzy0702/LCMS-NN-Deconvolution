"""Benchmark the full chain on synthetic runs with known truth.

Reports mass error, recall by abundance tier and processing time. Writes a Markdown table.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from lcmsdeconv.core.method import Method
from lcmsdeconv.evaluate import score_species
from lcmsdeconv.process import process_run
from lcmsdeconv.synth.chromatography import generate_run
from lcmsdeconv.synth.compounds import ClassConfig
from lcmsdeconv.synth.config import SynthConfig

PRESETS = {
    "protein_tof": (dict(classes=[ClassConfig("peptide", (8000.0, 80000.0))], mode="rplc",
                         polarity=1, instrument_kind="tof",
                         resolution_range=(20000.0, 40000.0)), "rplc_pos_protein"),
    "oligo_iprp": (dict(classes=[ClassConfig("ps_rna", (5000.0, 20000.0))], mode="iprp",
                        polarity=-1, instrument_kind="tof",
                        resolution_range=(20000.0, 40000.0)), "iprp_neg_oligo"),
    "polymer": (dict(classes=[ClassConfig("peg", (1500.0, 12000.0))], mode="polymer",
                     polarity=1, instrument_kind="tof",
                     resolution_range=(20000.0, 40000.0)), "polymer_pos"),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=3, help="runs per preset")
    ap.add_argument("--peaks", type=int, default=2)
    ap.add_argument("--minutes", type=float, default=3.0)
    ap.add_argument("--rate", type=float, default=1.0)
    ap.add_argument("--model", default=None)
    ap.add_argument("--out", default=None, type=Path)
    args = ap.parse_args()

    rows = []
    for preset, (kw, method_name) in PRESETS.items():
        method = Method.load(method_name)
        for i in range(args.runs):
            cfg = SynthConfig(**kw)
            rng = np.random.default_rng(1000 + i)
            run, truth = generate_run(cfg, rng, n_peaks=args.peaks,
                                      rt_range=(0.5, 0.5 + args.minutes),
                                      scan_rate_hz=args.rate)
            t0 = time.perf_counter()
            result = process_run(run, method, model_path=args.model)
            elapsed = time.perf_counter() - t0
            scores = score_species([s.to_dict() for s in result.species], truth.to_dict())
            rows.append({"preset": preset, "seed": 1000 + i, "seconds": elapsed,
                         "n_species": len(result.species), **scores})
            print(json.dumps(rows[-1], indent=2, default=float))

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(_markdown(rows), encoding="utf-8")
        print(f"wrote {args.out}")


def _markdown(rows: list[dict]) -> str:
    lines = ["# Synthetic benchmark", "",
             "Generated by `scripts/benchmark_synth.py`. Each row is one synthetic run scored",
             "against its own ground truth: a compound with its impurities eluting as one peak,",
             "processed with the matching bundled method.", "",
             "A component counts as found when its mass matches within 100 parts per million or",
             "0.5 Da, whichever is larger, and its retention time within half a minute. That",
             "tolerance is deliberately tight: a species reported one adduct away from its base",
             "mass counts as missed, which is the failure mode to watch.", "",
             "| Preset | Species found | Precision | Median abs. ppm | Recall >=10% | Recall 1-10% | Recall 0.1-1% | Seconds |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    def rec(tiers, name):
        t = tiers.get(name)
        return f"{t['recall']*100:.0f} %" if t else "-"

    for r in rows:
        tiers = r.get("tiers", {})
        ppm = r.get("median_abs_ppm")
        lines.append(
            f"| {r['preset']} | {r['n_species']} | {r.get('precision', 0)*100:.0f} % | "
            f"{ppm:.1f} | {rec(tiers, '>=10%')} | {rec(tiers, '1-10%')} | "
            f"{rec(tiers, '0.1-1%')} | {r['seconds']:.1f} |"
            if ppm is not None else
            f"| {r['preset']} | {r['n_species']} | {r.get('precision', 0)*100:.0f} % | - | "
            f"{rec(tiers, '>=10%')} | {rec(tiers, '1-10%')} | "
            f"{rec(tiers, '0.1-1%')} | {r['seconds']:.1f} |"
        )
    lines += ["", "## Reading this table", "",
              "**Recall >=10 %** is whether the main component was found and correctly named.",
              "**Recall 1-10 % and 0.1-1 %** are the impurity tiers, which is where a run stands",
              "or falls for purity work. **Precision** is the share of reported species that",
              "correspond to something real; the rest are envelopes fitted to noise or charge",
              "artefacts, and they are what a better charge assignment removes.", "",
              "Run with `--model <path.onnx>` to score a trained network against the",
              "deterministic estimator these numbers were produced with.", ""]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
