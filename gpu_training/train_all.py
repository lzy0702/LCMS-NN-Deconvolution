"""Train the charge networks on this computer's GPU, export them, and pack what to upload.

    gpu_training\\train_all.bat               (Windows)
    bash gpu_training/train_all.sh           (Linux)

The runs are those of RUN_TABLE (by default "window" and "comb": LadderNet at full size on
recipe v4, the whole-spectrum recipe with lone multiply charged oligonucleotides, with
isotope-charge channels, one in each view), one after the other; --runs chooses others, for
example --runs comb or --runs window,comb,window-plain. Run it again after a pause, a crash or a
reboot: a finished run is skipped and an interrupted one resumes where it stopped. To pause,
press Ctrl+C once (or put a file named PAUSE in the runs folder); the state is saved and the
program ends. The network trains on the GPU only; spectra are generated by data-worker
processes on the processor, as many as setup chose within the processor's cap and the RAM
budget (gpu_training/machine.json; --workers overrides it). The budget is setup's, by default
half the computer's memory, at least 16 GB and at most 48 (--ram-gb overrides it). If the
budget is reached anyway, the run pauses and resumes at once with two workers fewer. The ladder
scores all charges at once where setup measured that faster, with room to spare on the GPU,
and the GPU rather than the data workers sets the pace; HEAD_CHUNK at a time otherwise. A run
that runs out of GPU memory scoring them all at once continues in chunks from its last saved
state. Each run uses the GPU speedups setup measured faster on this GPU, with the same loss and
gradients, for its view (machine.json; none if it says nothing). Each finished run is exported
to ONNX (its parity with the checkpoint verified) and read once by the predictor over a whole
synthetic spectrum; the upload zip holds every finished run.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import signal
import subprocess
import sys
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
MACHINE = ROOT / "gpu_training" / "machine.json"
#: spectra per training step, the recipe's (setup measures the GPU memory of both views at it)
BATCH = 4
#: charges the ladder head scores at a time, recomputed in the backward pass: the same outputs
#: in about a third of the GPU memory, for about a third more time per step. A run scores all
#: charges at once instead where setup measured that faster, with room to spare, on a GPU that
#: sets the pace (head_chunk_for)
HEAD_CHUNK = 16
#: all charges at once only if the peak setup measured for that step (every spectrum at the
#: active-bin cap) times this stays under the GPU memory cap: room for the allocator's
#: fragmentation over a long run of spectra of every size
UNCHUNKED_MARGIN = 1.3
#: the CUDA context's share of the GPU memory cap (lcmsdeconv.nn.train._cap_gpu_memory)
CONTEXT_GB = 0.75
#: epochs and spectra per epoch of every run; all runs draw the same spectra (seed 0)
EPOCHS, TRAIN_LEN = 20, 6000
SPECTRA = EPOCHS * TRAIN_LEN
#: the recipe the runs train (train_charge_net.py --recipe). Setup records it in machine.json
#: ("recipe") with the data workers' speed on its spectra (RATE_KEY), so a machine.json from a
#: setup of another recipe gives no time estimate and asks for setup to run again
RECIPE = "v4"
RATE_KEY, RATE_WORKERS_KEY = f"{RECIPE}_spectra_per_second", f"{RECIPE}_workers"
#: what every run shares: the recipe at full size, singly charged ions labelled
COMMON = ["--recipe", RECIPE, "--arch", "ladder", "--model-size", "full", "--singly-charged",
          "keep", "--epochs", str(EPOCHS), "--train-len", str(TRAIN_LEN), "--val-len", "128",
          "--lr", "2e-3", "--seed", "0"]
#: the runs: the LadderNet view and whether it reads the isotope-charge channels
RUN_TABLE = {
    "window": {"view": "window", "iso": True, "out": f"runs/ladder_{RECIPE}_window.pt"},
    "comb": {"view": "comb", "iso": True, "out": f"runs/ladder_{RECIPE}_comb.pt"},
    "window-plain": {"view": "window", "iso": False,
                     "out": f"runs/ladder_{RECIPE}_window_plain.pt"},
    "comb-plain": {"view": "comb", "iso": False, "out": f"runs/ladder_{RECIPE}_comb_plain.pt"},
}
DEFAULT_RUNS = ("window", "comb")
#: the smoke version of a run: a few steps of tiny batches, written apart from the real runs
SMOKE_ARGS = ["--epochs", "1", "--train-len", "4", "--val-len", "2", "--batch-size", "2"]
PAUSED, MEMORY = 3, 4

interrupted = {"count": 0}
#: views whose run ran out of GPU memory scoring all charges at once in this train_all call
failed_views: set = set()


def make_run(name: str, smoke: bool = False) -> dict:
    """The run ``name`` of RUN_TABLE: its name, view, output, training arguments, head chunk and
    GPU speedups (main sets both from setup's measurements: head_chunk_for, speedups_for)."""
    spec = RUN_TABLE[name]
    out = spec["out"].replace("runs/ladder_", "runs/smoke_") if smoke else spec["out"]
    args = [*COMMON, "--view", spec["view"], *(["--iso-channels"] if spec["iso"] else [])]
    if smoke:
        args += SMOKE_ARGS
    return {"name": name, "view": spec["view"], "out": out, "args": args,
            "spectra": 4 if smoke else SPECTRA, "head_chunk": HEAD_CHUNK, "gpu_speedups": []}


def parse_runs(text: str | None) -> list[str]:
    """``"window,comb"`` -> ["window", "comb"]; SystemExit naming the known runs otherwise."""
    names = [t.strip() for t in (text or ",".join(DEFAULT_RUNS)).split(",") if t.strip()]
    unknown = [n for n in names if n not in RUN_TABLE]
    if unknown or not names:
        raise SystemExit(f"[train_all] unknown run {', '.join(unknown) or '(none)'}: choose "
                         f"from {', '.join(RUN_TABLE)} (default {','.join(DEFAULT_RUNS)})")
    return list(dict.fromkeys(names))


def on_ctrl_c(signum, frame):
    # the training process gets the same Ctrl+C and saves its state; wait for it
    interrupted["count"] += 1
    if interrupted["count"] > 1:
        raise KeyboardInterrupt
    print("\n[train_all] pause requested: waiting for the training to save its state ...",
          flush=True)


def stage_status(out: Path) -> str:
    """'new', 'paused' (a state to resume) or 'done', from the small status file training
    writes next to its state (so that this process never loads PyTorch: it would sit outside
    the RAM budget the training watches)."""
    if not out.with_suffix(".resume.pt").exists():
        return "new"
    try:
        st = json.loads(out.with_suffix(".status.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return "paused"  # resuming a finished run is harmless: it ends at once
    if st.get("stop_reason") == "finished" or st.get("epoch", 0) >= st.get("epochs", 1 << 30):
        return "done" if out.exists() else "paused"
    return "paused"


def pause_files() -> list[Path]:
    """PAUSE files in the runs folder: PAUSE, PAUSE.txt, PAUSE.txt.txt (Explorer hides the
    extension it adds), any case."""
    if not RUNS.exists():
        return []
    return [f for f in RUNS.iterdir()
            if f.is_file() and f.name.lower().split(".")[0] == "pause"]


#: what PyTorch prints when the GPU runs out of memory
GPU_OUT_OF_MEMORY = ("OutOfMemoryError", "CUDA out of memory")


def run_stage(stage: dict, pool: dict, limits: list, device: str, restart: bool) -> int:
    """Run one training run to its end (or a pause); ``pool["workers"]`` is lowered if the RAM
    budget is reached, and a run that runs out of GPU memory scoring all charges at once
    continues in chunks of HEAD_CHUNK (``stage["head_chunk"]``)."""
    out = ROOT / stage["out"]
    status = "new" if restart else stage_status(out)
    if status == "done":
        print(f"[train_all] {stage['name']}: already finished ({stage['out']})", flush=True)
        return 0
    log = out.with_suffix(".console.log")
    started = time.time()
    while True:
        flag = ["--resume"] if status == "paused" else ["--restart"]
        workers = pool["workers"]
        chunk = stage.get("head_chunk")
        speedups = list(stage.get("gpu_speedups") or [])
        cmd = [sys.executable, "scripts/train_charge_net.py", "--device", device,
               *stage["args"], *(["--head-chunk", str(chunk)] if chunk else []),
               "--gpu-speedups", ",".join(speedups) or "none",
               "--workers", str(workers), *limits, "--out", stage["out"],
               "--keep-pause-files", *flag]
        word = "resuming" if status == "paused" else "starting"
        how = f"{chunk} charges at a time" if chunk else "all charges at once"
        fast = f"GPU speedups {', '.join(speedups)}" if speedups else "no GPU speedups"
        print(f"[train_all] {stage['name']}: {word} with {workers} data workers, scoring {how}; "
              f"{fast}", flush=True)
        env = dict(os.environ, PYTHONUTF8="1", PYTHONUNBUFFERED="1")
        out_of_gpu_memory = False
        with open(log, "a", encoding="utf-8") as fh:
            fh.write(f"\n=== {datetime.datetime.now():%Y-%m-%d %H:%M} {' '.join(cmd)}\n")
            proc = subprocess.Popen(cmd, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True, encoding="utf-8",
                                    errors="replace", env=env)
            for line in proc.stdout:
                print(line, end="", flush=True)
                fh.write(line)
                out_of_gpu_memory |= any(t in line for t in GPU_OUT_OF_MEMORY)
            rc = proc.wait()
        if (rc not in (0, PAUSED, MEMORY) and out_of_gpu_memory and not chunk
                and not interrupted["count"]):
            stage["head_chunk"] = HEAD_CHUNK
            failed_views.add(stage["view"])
            kept = _remember_unchunked_failure(stage["view"])
            # resume from the last state this run saved, if any (not one a restart set aside)
            resume = out.with_suffix(".resume.pt")
            saved = resume.exists() and (not restart or resume.stat().st_mtime >= started)
            status = stage_status(out) if saved else "new"
            note = ("remembered in machine.json for this view" if kept else
                    "machine.json could not be written, so later runs try all at once again")
            print(f"[train_all] {stage['name']}: the GPU ran out of memory scoring all charges "
                  f"at once; continuing with {HEAD_CHUNK} at a time ({note})", flush=True)
            continue
        if rc == MEMORY and workers > 1 and not interrupted["count"]:
            pool["workers"] = max(1, workers - 2)
            status = "paused"
            print(f"[train_all] {stage['name']}: the RAM budget was reached; resuming with "
                  f"{pool['workers']} worker{'s' if pool['workers'] > 1 else ''}", flush=True)
            _remember_workers(pool["workers"])
            continue
        if rc == MEMORY:
            print(f"[train_all] {stage['name']}: the training process and {workers} worker "
                  f"already need more than the RAM budget; it is too low for this training "
                  f"(see gpu_training/machine.json). Raise it with --ram-gb, then run "
                  f"train_all again.", flush=True)
            return PAUSED
        return rc


def single_instance(lock_path: Path):
    """Hold an exclusive lock for as long as this process runs, or return None if another
    train_all already holds it (two runs would share state files and double the RAM)."""
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    fh = open(lock_path, "a+")
    try:
        if sys.platform == "win32":
            import msvcrt

            fh.seek(0)
            msvcrt.locking(fh.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl

            fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        fh.close()
        return None
    return fh  # the lock lasts while this handle is open


def _remember(update) -> bool:
    """Apply ``update`` to machine.json's contents and write them back; False if that failed."""
    try:
        info = json.loads(MACHINE.read_text(encoding="utf-8")) if MACHINE.exists() else {}
        update(info)
        MACHINE.write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
        return True
    except (OSError, ValueError):
        return False


def _remember_workers(workers: int) -> None:
    _remember(lambda info: info.__setitem__("workers", workers))


def _remember_unchunked_failure(view: str) -> bool:
    def update(info):
        failed = info.get("unchunked_failed") or []
        info["unchunked_failed"] = failed if view in failed else [*failed, view]
    return _remember(update)


def rate_workers(machine: dict) -> int:
    """The number of data workers whose speed setup measured on this recipe's spectra
    (RATE_WORKERS_KEY, the number it chose), 0 without a record."""
    return int(machine.get(RATE_WORKERS_KEY) or machine.get("workers") or 0)


def data_rate(machine: dict, workers: int) -> float | None:
    """Spectra per second ``workers`` data workers deliver: setup's measurement on this recipe's
    spectra, of rate_workers workers, in proportion for another number (None without one, as
    from a setup of an earlier recipe). For more workers than measured that is an upper bound,
    and an overestimate on a processor with efficiency cores, where each further worker adds
    less; for fewer, a lower bound."""
    rate, measured_workers = machine.get(RATE_KEY), rate_workers(machine)
    if not rate or not measured_workers:
        return None
    return float(rate) * workers / measured_workers


#: what sets a run's pace (run_pace), in time_estimate's words
PACE_SETTERS = {"workers": "set by the data workers",
                "gpu": "set by the GPU on setup's first training batch",
                "gpu_cap": "set by the GPU at the active-bin cap",
                "either": "set by the GPU or by the data workers"}


def speedup_name(speedups) -> str:
    """How setup names a combination of GPU speedups in machine.json (``speedup_timings``,
    ``speedup_checks``): "tf32+index_select", in GPU_SPEEDUPS order; "none" for none."""
    from lcmsdeconv.nn.train import GPU_SPEEDUPS

    return "+".join(s for s in GPU_SPEEDUPS if s in speedups) or "none"


def gpu_rates(machine: dict, stage: dict) -> dict:
    """The GPU's speed in a run of ``stage`` as setup measured it, in spectra per second (None
    where not measured): ``"batch"``, a training step on the runs' first training batch with the
    run's GPU speedups and head chunking (``speedup_timings``, measured with the chunking of
    ``head_chunks``), and ``"cap"``, a step with every spectrum at the active-bin cap, the
    slowest a step can be (``gpu_views``); ``"batch_ms"`` and ``"cap_ms"`` are the two steps'
    milliseconds. A step of more spectra takes about as much longer, so the rates stand for
    other batch sizes too."""
    view, chunk = stage["view"], stage.get("head_chunk", HEAD_CHUNK)
    out = {"batch": None, "batch_ms": None, "cap": None, "cap_ms": None}
    m = gpu_measurement(machine, view)
    if m and chunk is None:
        m = m.get("unchunked") or {}
    if m and m.get("step_seconds") and m.get("batch"):
        out["cap_ms"] = 1000.0 * float(m["step_seconds"])
        out["cap"] = float(m["batch"]) / float(m["step_seconds"])
    chunks = machine.get("head_chunks") or {}
    ms = ((machine.get("speedup_timings") or {}).get(view) or {}).get(
        speedup_name(stage.get("gpu_speedups") or []))
    if ms and machine.get("gpu_batch") and view in chunks and chunks[view] == chunk:
        out["batch_ms"] = float(ms)
        out["batch"] = float(machine["gpu_batch"]) / (float(ms) / 1000.0)
    return out


def run_pace(stage: dict, machine: dict, data: float, data_at_most: bool = False) -> dict:
    """The pace of a run of ``stage`` with data workers delivering ``data`` spectra per second:
    the slower of the workers and the GPU (gpu_rates: on the runs' first training batch where
    setup measured it, else at the active-bin cap) as ``pace``, which of the two sets it as
    ``set_by`` (a key of PACE_SETTERS), and as ``slowest`` the pace should every step take as
    long as at the active-bin cap; with gpu_rates' measurements and ``data``. Where ``data`` is
    only an upper bound (``data_at_most``: scaled up from fewer workers, data_rate), a GPU
    slower than it does not set the pace for certain: ``"either"`` may."""
    g = gpu_rates(machine, stage)
    gpu = g["batch"] or g["cap"]
    pace = min(data, gpu) if gpu else data
    set_by = "workers" if not gpu or data <= gpu else ("gpu" if g["batch"] else "gpu_cap")
    if data_at_most and set_by != "workers":
        set_by = "either"
    slowest = min(pace, g["cap"]) if g["cap"] else pace
    return {**g, "data": data, "pace": pace, "set_by": set_by, "slowest": slowest}


def training_hours(stages: list, machine: dict, workers: int) -> dict | None:
    """Hours of training for ``stages`` with ``workers`` data workers (data_rate), each run at
    its pace (run_pace) plus a tenth for validation: ``hours``, and ``slowest`` should every step
    take as long as at the active-bin cap; ``runs`` holds each run's name, view, hours and pace.
    With more workers than setup measured their rate is an upper bound, and so is each pace.
    None without setup's measurement of the workers on this recipe."""
    data = data_rate(machine, workers)
    if not data:
        return None
    at_most = workers > rate_workers(machine)
    runs, total, slowest = [], 0.0, 0.0
    for st in stages:
        p = run_pace(st, machine, data, at_most)
        hours = 1.1 * st["spectra"] / max(p["pace"], 1e-6) / 3600
        total += hours
        slowest += 1.1 * st["spectra"] / max(p["slowest"], 1e-6) / 3600
        runs.append({"name": st["name"], "view": st["view"], "hours": hours, **p})
    return {"hours": total, "slowest": slowest, "runs": runs}


def speedups_for(machine: dict, view: str) -> list[str]:
    """The GPU speedups a run of ``view`` trains with: those setup measured for that view at
    least 3 % faster on this GPU with the same loss and gradients (``gpu_speedups`` in
    machine.json, written by probe.py); none where it chose none or measured none."""
    from lcmsdeconv.nn.train import GPU_SPEEDUPS

    chosen = machine.get("gpu_speedups")
    chosen = chosen.get(view) if isinstance(chosen, dict) else None
    return [s for s in GPU_SPEEDUPS if s in (chosen or [])]


def head_chunk_for(machine: dict, view: str, gpu_gb: float, batch: int,
                   rate: float | None = None) -> int | None:
    """The head chunk a run of ``view`` trains with: None (all charges at once) where setup
    measured that step on this GPU, at ``batch`` spectra or more, faster than the chunked one and
    with its peak times UNCHUNKED_MARGIN under the cap (``gpu_gb`` less the CUDA context), and
    the chunked step is slower than the data workers' ``rate`` (spectra per second; None: not
    known). HEAD_CHUNK otherwise, and once a run of that view has run out of GPU memory
    unchunked."""
    m = gpu_measurement(machine, view)
    whole = (m or {}).get("unchunked") or {}
    if not (m and m.get("step_seconds") and whole.get("peak_gb") and whole.get("step_seconds")):
        return HEAD_CHUNK
    if view in (machine.get("unchunked_failed") or []) or batch > int(whole.get("batch") or 0):
        return HEAD_CHUNK
    if float(whole["peak_gb"]) * UNCHUNKED_MARGIN > gpu_gb - CONTEXT_GB:
        return HEAD_CHUNK
    if float(whole["step_seconds"]) > 0.95 * float(m["step_seconds"]):
        return HEAD_CHUNK  # not worth it
    if rate and float(m["batch"]) / float(m["step_seconds"]) >= rate:
        return HEAD_CHUNK  # the data workers set the pace: chunks cost no time
    return None


def export(stage: dict, force: bool = False) -> Path | None:
    """Export a finished run to ONNX (and its JSON sidecar) unless that is already done (or
    ``force``), verifying that the ONNX model computes what the checkpoint does, then read a
    whole synthetic spectrum with it through the predictor (gpu_training/check_model.py). Until
    both checks have passed the run carries a ``.unchecked`` marker (packed in the upload): a
    model that failed the predictor check, or whose export or checks were interrupted, is kept
    but exported and checked again next time."""
    ckpt = ROOT / stage["out"]
    onnx = ckpt.with_suffix(".onnx")
    unchecked = ckpt.with_suffix(".unchecked")
    if not ckpt.exists():
        return None
    env = dict(os.environ, PYTHONWARNINGS="ignore", PYTHONUTF8="1")
    if (force or unchecked.exists() or not onnx.exists()
            or onnx.stat().st_mtime < ckpt.stat().st_mtime):
        unchecked.write_text("export or check not finished\n", encoding="utf-8")
        print(f"[train_all] exporting {ckpt.name} to ONNX and checking it against the "
              f"checkpoint", flush=True)
        rc = subprocess.run([sys.executable, "-m", "lcmsdeconv.cli", "export-onnx", str(ckpt),
                             "-o", str(onnx), "--strict"], cwd=ROOT, env=env).returncode
        if rc != 0:
            print(f"[train_all] the export of {ckpt.name} failed (exit code {rc})", flush=True)
            onnx.unlink(missing_ok=True)  # tried again next time
            unchecked.write_text(f"export-onnx exit code {rc}\n", encoding="utf-8")
            return None
        rc = subprocess.run([sys.executable, "gpu_training/check_model.py", str(onnx)], cwd=ROOT,
                            env=env).returncode
        if rc != 0:
            print(f"[train_all] the predictor could not read a spectrum with {onnx.name} "
                  f"(exit code {rc})", flush=True)
            unchecked.write_text(f"check_model.py exit code {rc}\n", encoding="utf-8")
            return None
        unchecked.unlink(missing_ok=True)
    return onnx


def finished_runs(stages: list, smoke: bool = False) -> list:
    """``stages`` and every other run of RUN_TABLE finished earlier (the upload holds them all)."""
    names = [st["name"] for st in stages]
    others = [make_run(n, smoke=smoke) for n in RUN_TABLE if n not in names]
    return stages + [st for st in others if stage_status(ROOT / st["out"]) == "done"]


def pack(stages: list, tag: str) -> Path:
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M")
    zpath = RUNS / f"upload_{tag}{stamp}.zip"
    with zipfile.ZipFile(zpath, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for stage in stages:
            base = ROOT / stage["out"]
            for suffix in (".pt", ".onnx", ".json", ".log.jsonl", ".console.log", ".status.json",
                           ".unchecked"):
                f = base.with_suffix(suffix)
                if f.exists():
                    zf.write(f, f"runs/{f.name}")
        for f in (MACHINE, ROOT / "gpu_training" / "setup.log"):
            if f.exists():
                zf.write(f, f"gpu_training/{f.name}")
    return zpath


def gpu_measurement(machine: dict, view: str) -> dict | None:
    """What setup measured on the GPU for ``view`` at the recipe's batch: ``{"batch", "peak_gb",
    "step_seconds"}``, or None (no measurement, or one of an earlier package)."""
    m = (machine.get("gpu_views") or {}).get(view)
    return m if m and m.get("peak_gb") and m.get("batch") else None


def batch_problem(batch: int, machine: dict, gpu_gb: float, view: str = "window") -> str | None:
    """Why ``batch`` spectra per step of the ``view`` LadderNet would not fit under the GPU
    memory cap, or None. The peak setup measured for that view (at its batch) is scaled in
    proportion (an overestimate for a larger batch: part of it, the network and the CUDA
    context, does not grow with the batch)."""
    if batch < 1:
        return "the batch size must be at least 1"
    m = gpu_measurement(machine, view)
    if m is None:
        return None
    peak, measured = float(m["peak_gb"]), int(m["batch"])
    if batch <= measured and peak <= gpu_gb:
        return None  # measured under this cap
    need = peak * batch / measured
    if need <= gpu_gb:
        return None
    largest = max(1, int(measured * gpu_gb / peak))
    return (f"the {view} view at {batch} spectra per step needs about {need:.1f} GB of GPU "
            f"memory (setup measured {peak:g} GB at {measured}), more than the cap of "
            f"{gpu_gb:g} GB: use at most --batch-size {largest}, or raise the cap with "
            f"--gpu-memory-gb")


def time_estimate(stages: list, machine: dict, workers: int,
                  remeasure: str | None = None) -> str | None:
    """training_hours in words: each run's hours at its pace and what sets the pace, the hours
    should every step take as long as at the active-bin cap (where that is longer), and whether
    the data workers' rate is scaled from another number of workers than setup measured. Scaled
    up it may promise too much, and ``remeasure``, the command that measures that many, is
    named."""
    est = training_hours(stages, machine, workers)
    if est is None:
        return None
    parts = [f"{r['name']} {r['hours']:.1f} h at {r['pace']:.0f} spectra/s, "
             f"{PACE_SETTERS[r['set_by']]}" for r in est["runs"]]
    text = f"about {est['hours']:.1f} h of training from the start ({'; '.join(parts)})"
    if est["slowest"] > 1.05 * est["hours"]:
        text += (f"; up to {est['slowest']:.1f} h should every step take as long as with every "
                 f"spectrum at the active-bin cap")
    measured = rate_workers(machine)
    if measured and measured != workers:
        text += f"; the data workers' rate is setup's for {measured}, scaled to {workers}"
    if measured and workers > measured:
        text += (": an upper bound (on a processor with efficiency cores each further worker "
                 "adds less), so the time may be longer")
        if any(r["set_by"] == "either" for r in est["runs"]):
            text += " and the data workers may set the pace"
        if remeasure:
            text += f"; to measure {workers}: {remeasure}"
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--runs", default=None,
                    help=f"the runs to train, in order, comma-separated: "
                         f"{', '.join(RUN_TABLE)} (default {','.join(DEFAULT_RUNS)})")
    ap.add_argument("--workers", type=int, default=None,
                    help="data workers (default: gpu_training/machine.json, from setup)")
    ap.add_argument("--batch-size", type=int, default=BATCH,
                    help=f"spectra per training step (default {BATCH}, the recipe's); the "
                         "learning rate stays the recipe's, and a run already started at "
                         "another size needs --restart")
    ap.add_argument("--ram-gb", type=float, default=None,
                    help="RAM budget of the training process and its data workers together "
                         "(default: setup's, in machine.json; without one, half this computer's "
                         "memory, at least 16 GB and at most 48)")
    ap.add_argument("--gpu-memory-gb", type=float, default=None,
                    help="GPU memory cap (default: machine.json, else 14)")
    ap.add_argument("--restart", action="store_true",
                    help="discard the saved states of the chosen runs and train them afresh")
    ap.add_argument("--smoke", action="store_true",
                    help="a tiny run of the whole procedure (setup runs it)")
    ap.add_argument("--resume", action="store_true", help=argparse.SUPPRESS)  # always resumes
    ap.add_argument("--only", default=None, help=argparse.SUPPRESS)  # the two-stage recipe's
    ap.add_argument("--device", default="cuda", help=argparse.SUPPRESS)  # cpu: tests only
    args = ap.parse_args()
    if args.only:
        print("[train_all] run_stage1 / run_stage2 belong to the earlier two-stage recipe, which "
              "this package no longer trains (delete them). Use train_all with --runs, for "
              f"example --runs comb; the runs are {', '.join(RUN_TABLE)}.", flush=True)
        return 1
    names = parse_runs(args.runs)
    stages = [make_run(n, smoke=args.smoke) for n in names]

    machine = json.loads(MACHINE.read_text(encoding="utf-8")) if MACHINE.exists() else {}
    sys.path.insert(0, str(ROOT / "src"))
    from lcmsdeconv.nn.machine import (
        MAIN_GB,
        auto_workers,
        cpu_workers,
        default_ram_budget_gb,
        ram_workers,
    )

    default_ram = default_ram_budget_gb()
    ram = args.ram_gb or machine.get("ram_budget_gb") or default_ram
    gpu = args.gpu_memory_gb or machine.get("gpu_memory_gb") or 14.0
    if not args.smoke:
        for view in dict.fromkeys(st["view"] for st in stages):
            problem = batch_problem(args.batch_size, machine, gpu, view)
            if problem:
                print(f"[train_all] {problem}.", flush=True)
                return 1

    workers = args.workers or machine.get("workers")
    if not args.workers and machine.get("worker_gb") and ram != machine.get("ram_budget_gb"):
        # another budget than setup measured for: as many workers as it holds, by the
        # memory measured for the training process and for one worker
        fit = ram_workers(ram, machine["worker_gb"], machine.get("main_gb", MAIN_GB))
        workers = max(1, min(cpu_workers(), fit))
    if workers is None:
        workers = auto_workers(ram)
    rate = data_rate(machine, int(workers))
    for st in stages:  # the smoke checks the choices training makes, at the recipe's batch
        st["head_chunk"] = head_chunk_for(machine, st["view"], gpu, args.batch_size, rate)
        st["gpu_speedups"] = speedups_for(machine, st["view"])
    lock = single_instance(RUNS / ".train_all.lock")
    if lock is None:
        print("[train_all] a training is already running in another window; this one stops.",
              flush=True)
        return 1
    limits = ["--max-ram-gb", f"{ram:g}"]
    if args.device == "cuda":
        limits += ["--max-gpu-memory-gb", f"{gpu:g}"]
    if not args.smoke:  # the smoke runs keep their own tiny batches
        limits += ["--batch-size", str(args.batch_size)]
    RUNS.mkdir(exist_ok=True)
    for f in pause_files():  # left from an earlier pause; a new one pauses this run
        f.unlink()
        print(f"[train_all] removed {f.name} left from the last pause", flush=True)
    batch = "" if args.smoke else f", {args.batch_size} spectra per step"
    print(f"[train_all] runs: {', '.join(names)}{' (smoke)' if args.smoke else ''}; GPU "
          f"training, {workers} data workers{batch}, RAM budget {ram:g} GB, GPU memory cap "
          f"{gpu:g} GB", flush=True)
    if not args.smoke:
        probe = (r".venv\Scripts\python gpu_training\probe.py" if sys.platform == "win32"
                 else ".venv/bin/python gpu_training/probe.py")
        remeasure = (f"{probe} --ram-gb {ram:g} --gpu-memory-gb {gpu:g}"
                     + (f" --workers {workers}" if args.workers else ""))
        estimate = time_estimate(stages, machine, int(workers), remeasure)
        if estimate:
            print(f"[train_all] {estimate}; each epoch then reports the time left and what set "
                  f"its pace", flush=True)
        elif MACHINE.exists():
            print(f"[train_all] gpu_training/machine.json holds no measurement of this recipe "
                  f"({RECIPE}; an earlier package's setup): run setup again (setup_and_train "
                  f"does it by itself) for the time estimate and the GPU memory check",
                  flush=True)
        budget = machine.get("ram_budget_gb")
        if (not args.ram_gb and budget and "ram_budget_default" not in machine
                and float(budget) < default_ram):
            # an earlier setup's budget, 16 GB by default whatever the computer
            print(f"[train_all] gpu_training/machine.json comes from an earlier setup, with a RAM "
                  f"budget of {float(budget):g} GB; setup now takes half the computer's memory "
                  f"by default, {default_ram:g} GB here, for more data workers: run setup again "
                  f"(setup_and_train does it by itself), or train with --ram-gb "
                  f"{default_ram:g}", flush=True)
    if "gpu_speedups" not in machine:
        print("[train_all] no GPU speedups: gpu_training/machine.json does not say which are "
              "faster on this GPU; running setup again measures them", flush=True)
    signal.signal(signal.SIGINT, on_ctrl_c)

    pool = {"workers": int(workers)}
    failed = []
    try:
        for stage in stages:
            if stage["head_chunk"] is None and stage["view"] in failed_views:
                stage["head_chunk"] = HEAD_CHUNK  # an earlier run of this view ran out
            # the smoke always starts afresh, so that it checks this package's code
            rc = run_stage(stage, pool, limits, args.device, args.restart or args.smoke)
            # a pause asked for while the run was finishing (its last validation) or starting
            # up still stops here, before the next run
            if rc == PAUSED or interrupted["count"] or (rc == 0 and pause_files()):
                print(f"[train_all] paused in {stage['name']}. Run train_all again to continue.",
                      flush=True)
                return PAUSED
            if rc != 0:
                log = (ROOT / stage["out"]).with_suffix(".console.log")
                print(f"[train_all] {stage['name']} stopped with an error (exit code {rc}); its "
                      f"output is in {log}", flush=True)
                return rc
            if export(stage, force=args.smoke) is None:
                failed.append(stage["name"])
    except KeyboardInterrupt:
        print("\n[train_all] aborted (Ctrl+C twice); the last saved state is kept, run "
              "train_all again to continue from it.", flush=True)
        return 130
    zpath = pack(finished_runs(stages, args.smoke), "smoke_" if args.smoke else "")
    if failed:
        print(f"[train_all] the export or the predictor check of {', '.join(failed)} failed "
              f"(see above); the checkpoints are packed in {zpath}", flush=True)
        return 1
    print(f"[train_all] done. Upload this file: {zpath}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
