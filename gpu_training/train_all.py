"""Train both stages on this computer's GPU, export the networks, and pack what to upload.

    gpu_training\\train_all.bat               (Windows)
    bash gpu_training/train_all.sh           (Linux)

Run it again after a pause, a crash or a reboot: a finished stage is skipped and an
interrupted one resumes where it stopped. To pause, press Ctrl+C once (or put a file named
PAUSE in the runs folder); the state is saved and the program ends. The network trains on the
GPU only; spectra are generated by data-worker processes on the processor, as many as fit the
RAM budget (gpu_training/machine.json, written by setup.py; --workers overrides it). If the
budget is reached anyway, the stage pauses and resumes at once with two workers fewer.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import signal
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
MACHINE = ROOT / "gpu_training" / "machine.json"
COMMON = ["--arch", "ladder", "--model-size", "full", "--val-len", "128", "--batch-size", "8"]
#: the two stages: 240 000 new spectra for stage 1, 96 000 with dense background for stage 2
STAGES = [
    {"name": "stage 1", "out": "runs/ladder_full_ignore.pt", "spectra": 40 * 6000,
     "args": ["--singly-charged", "ignore", "--epochs", "40", "--train-len", "6000",
              "--lr", "2e-3"]},
    {"name": "stage 2", "out": "runs/ladder_full_stage2.pt", "spectra": 16 * 6000,
     "args": ["--singly-charged", "keep", "--background-ions", "200",
              "--init", "runs/ladder_full_ignore.pt", "--epochs", "16", "--train-len", "6000",
              "--lr", "5e-4"]},
]
SMOKE = [
    {"name": "smoke stage 1", "out": "runs/smoke_stage1.pt", "spectra": 2 * 8,
     "args": ["--singly-charged", "ignore", "--epochs", "2", "--train-len", "8", "--lr", "2e-3",
              "--val-len", "4", "--batch-size", "2"]},
    {"name": "smoke stage 2", "out": "runs/smoke_stage2.pt", "spectra": 2 * 8,
     "args": ["--singly-charged", "keep", "--background-ions", "200",
              "--init", "runs/smoke_stage1.pt", "--epochs", "2", "--train-len", "8",
              "--lr", "5e-4", "--val-len", "4", "--batch-size", "2"]},
]
PAUSED, MEMORY = 3, 4

interrupted = {"count": 0}


def on_ctrl_c(signum, frame):
    # the training process gets the same Ctrl+C and saves its state; wait for it
    interrupted["count"] += 1
    if interrupted["count"] > 1:
        raise KeyboardInterrupt
    print("\n[train_all] pause requested: waiting for the training to save its state ...",
          flush=True)


def stage_status(out: Path) -> str:
    """'new', 'paused' (a state to resume) or 'done'."""
    resume = out.with_suffix(".resume.pt")
    if not resume.exists():
        return "new"
    import torch

    st = torch.load(resume, map_location="cpu", weights_only=False)
    if st.get("stop_reason") == "finished" or st.get("epoch", 0) >= st["config"]["epochs"]:
        return "done" if out.exists() else "paused"
    return "paused"


def run_stage(stage: dict, pool: dict, limits: list, device: str, restart: bool,
              after: Path | None = None) -> int:
    """Run one stage to its end (or a pause); ``pool["workers"]`` is lowered if the RAM budget
    is reached. ``after`` is the checkpoint the stage starts from: if that is newer than the
    stage's own state, the earlier stage was trained again and this one starts afresh."""
    out = ROOT / stage["out"]
    status = "new" if restart else stage_status(out)
    state = out.with_suffix(".resume.pt")
    if (status != "new" and after is not None and after.exists() and state.exists()
            and after.stat().st_mtime > state.stat().st_mtime):
        print(f"[train_all] {stage['name']}: the stage before it was trained again, so it "
              f"starts afresh", flush=True)
        status = "new"
    if status == "done":
        print(f"[train_all] {stage['name']}: already finished ({stage['out']})", flush=True)
        return 0
    log = out.with_suffix(".console.log")
    while True:
        flag = ["--resume"] if status == "paused" else ["--restart"]
        workers = pool["workers"]
        cmd = [sys.executable, "scripts/train_charge_net.py", "--device", device, *COMMON,
               *stage["args"], "--workers", str(workers), *limits, "--out", stage["out"], *flag]
        word = "resuming" if status == "paused" else "starting"
        print(f"[train_all] {stage['name']}: {word} with {workers} data workers", flush=True)
        env = dict(os.environ, PYTHONUTF8="1", PYTHONUNBUFFERED="1")
        with open(log, "a", encoding="utf-8") as fh:
            fh.write(f"\n=== {datetime.datetime.now():%Y-%m-%d %H:%M} {' '.join(cmd)}\n")
            proc = subprocess.Popen(cmd, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True, encoding="utf-8",
                                    errors="replace", env=env)
            for line in proc.stdout:
                print(line, end="", flush=True)
                fh.write(line)
            rc = proc.wait()
        if rc == MEMORY and workers > 1 and not interrupted["count"]:
            pool["workers"] = max(1, workers - 2)
            status = "paused"
            print(f"[train_all] {stage['name']}: the RAM budget was reached; resuming with "
                  f"{pool['workers']} worker{'s' if pool['workers'] > 1 else ''}", flush=True)
            _remember_workers(pool["workers"])
            continue
        if rc == MEMORY:
            print(f"[train_all] {stage['name']}: the RAM budget was reached with "
                  f"{workers} worker(s); raise it with --ram-gb, then run train_all again.",
                  flush=True)
            return PAUSED
        return rc


def _remember_workers(workers: int) -> None:
    try:
        info = json.loads(MACHINE.read_text(encoding="utf-8")) if MACHINE.exists() else {}
        info["workers"] = workers
        MACHINE.write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
    except (OSError, ValueError):
        pass


def export(stage: dict) -> Path | None:
    ckpt = ROOT / stage["out"]
    onnx = ckpt.with_suffix(".onnx")
    if not ckpt.exists():
        return None
    if not onnx.exists() or onnx.stat().st_mtime < ckpt.stat().st_mtime:
        print(f"[train_all] exporting {ckpt.name} to ONNX", flush=True)
        env = dict(os.environ, PYTHONWARNINGS="ignore", PYTHONUTF8="1")
        rc = subprocess.run([sys.executable, "-m", "lcmsdeconv.cli", "export-onnx", str(ckpt),
                             "-o", str(onnx)], cwd=ROOT, env=env).returncode
        if rc != 0:
            print(f"[train_all] the export of {ckpt.name} failed (exit code {rc})", flush=True)
            return None
    return onnx


def pack(stages: list, tag: str) -> Path:
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M")
    zpath = RUNS / f"upload_{tag}{stamp}.zip"
    with zipfile.ZipFile(zpath, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for stage in stages:
            base = ROOT / stage["out"]
            for suffix in (".pt", ".onnx", ".json", ".log.jsonl", ".console.log"):
                f = base.with_suffix(suffix)
                if f.exists():
                    zf.write(f, f"runs/{f.name}")
        for f in (MACHINE, ROOT / "gpu_training" / "setup.log"):
            if f.exists():
                zf.write(f, f"gpu_training/{f.name}")
    return zpath


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--workers", type=int, default=None,
                    help="data workers (default: gpu_training/machine.json, from setup)")
    ap.add_argument("--ram-gb", type=float, default=None,
                    help="RAM budget (default: machine.json, else 16)")
    ap.add_argument("--gpu-memory-gb", type=float, default=None,
                    help="GPU memory cap (default: machine.json, else 14)")
    ap.add_argument("--restart", action="store_true",
                    help="discard the saved states and train both stages from the beginning")
    ap.add_argument("--only", type=int, choices=[1, 2], default=None,
                    help="run only stage 1 or stage 2 (and export it)")
    ap.add_argument("--smoke", action="store_true", help="a tiny run of the whole procedure")
    ap.add_argument("--resume", action="store_true", help=argparse.SUPPRESS)  # always resumes
    ap.add_argument("--device", default="cuda", help=argparse.SUPPRESS)  # cpu: tests only
    args = ap.parse_args()

    machine = json.loads(MACHINE.read_text(encoding="utf-8")) if MACHINE.exists() else {}
    ram = args.ram_gb or machine.get("ram_budget_gb") or 16.0
    gpu = args.gpu_memory_gb or machine.get("gpu_memory_gb") or 14.0
    workers = args.workers or machine.get("workers")
    if workers is None:
        sys.path.insert(0, str(ROOT / "src"))
        from lcmsdeconv.nn.machine import auto_workers

        workers = auto_workers(ram)
    stages = SMOKE if args.smoke else STAGES
    if args.only:
        stages = [stages[args.only - 1]]
    limits = ["--max-ram-gb", f"{ram:g}"]
    if args.device == "cuda":
        limits += ["--max-gpu-memory-gb", f"{gpu:g}"]
    RUNS.mkdir(exist_ok=True)
    rate = machine.get("spectra_per_second")
    print(f"[train_all] GPU training, {workers} data workers, RAM budget {ram:g} GB, GPU memory "
          f"cap {gpu:g} GB", flush=True)
    if rate and not args.smoke:
        hours = sum(s["spectra"] for s in stages) / rate / 3600 * 1.1
        print(f"[train_all] about {hours:.1f} h in all at the measured {rate:.0f} spectra/s",
              flush=True)
    signal.signal(signal.SIGINT, on_ctrl_c)

    pool = {"workers": int(workers)}
    try:
        for k, stage in enumerate(stages):
            after = ROOT / stages[k - 1]["out"] if k > 0 else None
            rc = run_stage(stage, pool, limits, args.device, args.restart, after)
            if rc == PAUSED or (rc != 0 and interrupted["count"]):
                print(f"[train_all] paused in {stage['name']}. Run train_all again to continue.",
                      flush=True)
                return PAUSED
            if rc != 0:
                log = (ROOT / stage["out"]).with_suffix(".console.log")
                print(f"[train_all] {stage['name']} stopped with an error (exit code {rc}); its "
                      f"output is in {log}", flush=True)
                return rc
    except KeyboardInterrupt:
        print("\n[train_all] aborted (Ctrl+C twice); the last saved state is kept, run "
              "train_all again to continue from it.", flush=True)
        return 130
    for stage in stages:
        export(stage)
    if args.only:
        print(f"[train_all] {stages[0]['name']} done.", flush=True)
        return 0
    zpath = pack(stages, "smoke_" if args.smoke else "")
    print(f"[train_all] done. Upload this file: {zpath}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
